import 'dart:io';
import 'package:flutter/material.dart';
import 'package:path_provider/path_provider.dart';
import 'package:screenshot/screenshot.dart';
import 'package:share_plus/share_plus.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

class ShareService {
  static final ShareService instance = ShareService._();
  ShareService._();

  final ScreenshotController _screenshotController = ScreenshotController();

  /// Share a widget as an image
  Future<void> shareWidgetAsImage({
    required Widget widget,
    required String fileName,
  }) async {
    try {
      final image = await _screenshotController.captureFromWidget(
        Material(child: widget),
        delay: const Duration(milliseconds: 100),
      );

      final tempDir = await getTemporaryDirectory();
      final file = await File('${tempDir.path}/$fileName.png').create();
      await file.writeAsBytes(image);

      await Share.shareXFiles(
        [XFile(file.path)],
        text: 'Check out my monthly habit progress on Flow!',
      );
    } catch (e) {
      debugPrint('Error sharing image: $e');
      rethrow;
    }
  }

  /// Generate and share a PDF report
  Future<void> shareMonthlyPdfReport({
    required Map<String, dynamic> recap,
  }) async {
    try {
      final pdf = pw.Document();

      final monthName = recap['monthName'] ?? 'Monthly Recap';
      final totalRate = recap['totalCompletionRate'] ?? 0;
      final habitSummaries = recap['habitSummaries'] as List<dynamic>? ?? [];
      final aiInsight = recap['aiInsight'] as String? ?? '';

      pdf.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          build: (pw.Context context) {
            return pw.Padding(
              padding: const pw.EdgeInsets.all(32),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Row(
                    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                    children: [
                      pw.Text('FLOW', style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800)),
                      pw.Text(monthName, style: const pw.TextStyle(fontSize: 14, color: PdfColors.grey700)),
                    ],
                  ),
                  pw.SizedBox(height: 40),
                  pw.Center(
                    child: pw.Column(
                      children: [
                        pw.Text('Monthly Performance Report', style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold)),
                        pw.SizedBox(height: 10),
                        pw.Text('$totalRate% Success Rate', style: pw.TextStyle(fontSize: 32, fontWeight: pw.FontWeight.bold, color: _getPdfRateColor(totalRate))),
                      ],
                    ),
                  ),
                  pw.SizedBox(height: 40),
                  pw.Text('Habit Summaries', style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold)),
                  pw.Divider(),
                  pw.SizedBox(height: 10),
                  ...habitSummaries.map((s) {
                    return pw.Padding(
                      padding: const pw.EdgeInsets.symmetric(vertical: 4),
                      child: pw.Row(
                        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                        children: [
                          pw.Text(s['title'] ?? ''),
                          pw.Text('${s['completionRate']}% (${s['bestStreak']}d streak)', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
                        ],
                      ),
                    );
                  }).toList(),
                  if (aiInsight.isNotEmpty) ...[
                    pw.SizedBox(height: 40),
                    pw.Container(
                      padding: const pw.EdgeInsets.all(16),
                      decoration: pw.BoxDecoration(
                        color: PdfColors.grey100,
                        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
                      ),
                      child: pw.Column(
                        crossAxisAlignment: pw.CrossAxisAlignment.start,
                        children: [
                          pw.Text("COACH'S INSIGHT", style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800)),
                          pw.SizedBox(height: 8),
                          pw.Text(aiInsight, style: const pw.TextStyle(fontSize: 12, fontStyle: pw.FontStyle.italic)),
                        ],
                      ),
                    ),
                  ],
                  pw.Spacer(),
                  pw.Center(child: pw.Text('Generated by Flow Habit Tracker', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey500))),
                ],
              ),
            );
          },
        ),
      );

      final tempDir = await getTemporaryDirectory();
      final file = File('${tempDir.path}/Flow_Report_${monthName.replaceAll(' ', '_')}.pdf');
      await file.writeAsBytes(await pdf.save());

      await Share.shareXFiles(
        [XFile(file.path)],
        text: 'My Monthly Habit Report from Flow',
      );
    } catch (e) {
      debugPrint('Error sharing PDF: $e');
      rethrow;
    }
  }

  PdfColor _getPdfRateColor(int rate) {
    if (rate >= 80) return PdfColors.green;
    if (rate >= 50) return PdfColors.orange;
    return PdfColors.red;
  }
}
